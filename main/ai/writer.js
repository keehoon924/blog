async function generatePost(subject, perspective = '', style, category = 'other', learningBoost = '', relatedKeywords = [], searchContext = '') {
  const client = getClient();
  const cat = CATEGORIES[category] || CATEGORIES.other;

  const lsiStr = relatedKeywords.length > 0
    ? `\nLSI 연관 키워드 (자연스럽게 2~3회 삽입): ${relatedKeywords.join(', ')}`
    : '';

  const perspectiveRule = perspective
    ? `\n관점/시각 (반드시 반영): "${perspective}"\n글 전체를 이 관점에서 전개하세요.`
    : '';

  const searchSection = searchContext
    ? `\n참고 정보 (자연스럽게 반영 — 정확한 정보 우선):\n${searchContext}`
    : '';

  const bodyStylesDesc = (cat.bodyStyles || []).map(s => `▶ ${s}: ${BODY_STYLES[s]}`).join('\n\n');

  const systemPrompt = `${COMMON_RULES}

${HOOK_PATTERNS}

---

카테고리: ${cat.name}
이 카테고리 우선 후킹 패턴: ${cat.hookPatterns}

본문 스타일 (아래 중 하나를 선택해 글 전체에 일관되게 적용):
${bodyStylesDesc}

문체 방향: ${cat.style}
글 구조: ${cat.structure}
소제목 형식: ${cat.subheadingFormat}
어조 예시: ${cat.toneExamples}

SEO 키워드: "${subject}"
- 본문 첫 100자 이내 자연스럽게 포함
- 전체 2~4회 자연스럽게 사용
- 제목에 직접 사용 금지 — 감정/결과/상황으로 표현${lsiStr}
${perspectiveRule}${searchSection}
${learningBoost ? `\n학습 개선:\n${learningBoost}` : ''}

기술 형식 (필수):
- 마크다운 완전 금지: #, ##, >, *, _, ~~, \`\`\` 사용 금지
- 볼드: **텍스트** 형식으로만 (소제목, 핵심 수치에만 최소한으로)
- 소제목마다 이미지 플레이스홀더: [이미지: ${cat.imageHint}]
- 마지막에 독자 질문 1개 + "공감과 이웃추가 부탁드려요 😊"

응답 형식 (정확히):
TITLE: [제목]
CONTENT: [본문]
HASHTAGS: [#태그1 #태그2 ... #태그10]`;

  const userPrompt = `소재: "${subject}"
${perspective ? `관점: "${perspective}"` : ''}

위 소재로 네이버 블로그 글을 작성해주세요.
- 순수 텍스트 1500자 이상
- 소제목 3~5개
- 해시태그 10개`;

  const response = await client.chat.completions.create({
    model: 'gpt-4.1',
    messages: [
      { role: 'system', content: systemPrompt },
      { role: 'user', content: userPrompt },
    ],
    temperature: 0.85,
    max_tokens: 3000,
  });

  const text = response.choices[0].message.content;
  const titleMatch = text.match(/TITLE:\s*(.+)/);
  const contentMatch = text.match(/CONTENT:\s*([\s\S]+?)(?=\nHASHTAGS:|$)/);
  const hashtagsMatch = text.match(/HASHTAGS:\s*(.+)/);

  return {
    title: titleMatch ? titleMatch[1].trim() : subject,
    content: contentMatch ? contentMatch[1].trim() : text,
    hashtags: hashtagsMatch ? hashtagsMatch[1].trim() : '',
  };
}

